#!/usr/bin/env node
// Which ideas landed in which lane. Read-only.
//   node assimilation/cluster.mjs          summary to the screen
//   node assimilation/cluster.mjs --md     also writes assimilation/CLUSTERS.md
import fs from "node:fs";
import path from "node:path";
import { HERE, readAllUnits } from "./enumerate.mjs";
import { loadAnswers } from "./check.mjs";
import { expandAnswers } from "./expand.mjs";
const units = readAllUnits();
const { answered } = expandAnswers(units, loadAnswers());
const lanes = {};
const disp = {};
const conflicts = [];
const unanswered = {};
for (const u of units) {
  const rec = answered.get(u.id);
  if (!rec) {
    unanswered[u.source] = (unanswered[u.source] ?? 0) + 1;
    continue;
  }
  const key = rec.d === "dropped" ? "dropped:" + rec.why : rec.d;
  disp[key] = (disp[key] ?? 0) + 1;
  if (rec.d !== "absorbed") continue;
  const { skill, section } = rec.to;
  const lane = (lanes[skill] ??= {});
  const s = (lane[section] ??= { n: 0, from: new Set() });
  s.n++;
  s.from.add(u.source + ":" + u.skill);
  if (/\[conflict:/i.test(section)) conflicts.push([section, u.id]);
}
const lines = [];
for (const [lane, secs] of Object.entries(lanes).sort()) {
  const total = Object.values(secs).reduce((a, s) => a + s.n, 0);
  lines.push("## " + lane + ": " + total + " units, " + Object.keys(secs).length + " sections");
  for (const [sec, s] of Object.entries(secs).sort((a, b) => b[1].n - a[1].n)) lines.push("- " + sec + " (" + s.n + " units from " + s.from.size + " skills)");
  lines.push("");
}
console.log("units: " + units.length + "; dispositions: " + JSON.stringify(disp) + "; unanswered by pack: " + JSON.stringify(unanswered));
for (const [lane, secs] of Object.entries(lanes).sort()) {
  const total = Object.values(secs).reduce((a, s) => a + s.n, 0);
  const top = Object.entries(secs).sort((a, b) => b[1].n - a[1].n).slice(0, 4).map(([k, v]) => k + " (" + v.n + ")").join("; ");
  console.log(lane + ": " + total + " units, " + Object.keys(secs).length + " sections; top: " + top);
}
const cs = [...new Set(conflicts.map((c) => c[0]))];
console.log("conflict sections: " + cs.length + (cs.length ? "\n" + cs.slice(0, 15).join("\n") : ""));
if (process.argv.includes("--md")) fs.writeFileSync(path.join(HERE, "CLUSTERS.md"), "# Clusters (generated by cluster.mjs)\n\n" + lines.join("\n"));
