# PyYAML's YAML 1.1 patterns where ruamel's 1.1 tables differ (y/n booleans,
# floats without a dot), so GitHub's files parse as they did under pyyaml.
YAML11_PATTERNS = {
    "tag:yaml.org,2002:bool": r"""^(?:yes|Yes|YES|no|No|NO
        |true|True|TRUE|false|False|FALSE
        |on|On|ON|off|Off|OFF)$""",
    "tag:yaml.org,2002:float": r"""^(?:[-+]?(?:[0-9][0-9_]*)\.[0-9_]*(?:[eE][-+][0-9]+)?
        |\.[0-9][0-9_]*(?:[eE][-+][0-9]+)?
        |[-+]?[0-9][0-9_]*(?::[0-5]?[0-9])+\.[0-9_]*
        |[-+]?\.(?:inf|Inf|INF)
        |\.(?:nan|NaN|NAN))$""",
    "tag:yaml.org,2002:int": r"""^(?:[-+]?0b[0-1_]+
        |[-+]?0[0-7_]+
        |[-+]?(?:0|[1-9][0-9_]*)
        |[-+]?0x[0-9a-fA-F_]+
        |[-+]?[1-9][0-9_]*(?::[0-5]?[0-9])+)$""",
}


def keep_text(constructor, node):
    return constructor.construct_scalar(node)


def yaml11(constructor=None):
    """A pure-Python YAML 1.1 parser; ruamel ships a wheel for every interpreter."""
    from ruamel.yaml import YAML
    from ruamel.yaml.resolver import VersionedResolver

    class Resolver(VersionedResolver):
        def add_version_implicit_resolver(self, version, tag, regexp, first):
            if tag in YAML11_PATTERNS:
                regexp = re.compile(YAML11_PATTERNS[tag], re.X)
            super().add_version_implicit_resolver(version, tag, regexp, first)

    parser = YAML(typ="safe", pure=True)
    parser.version = (1, 1)
    parser.Resolver = Resolver
    if constructor:
        parser.Constructor = constructor
    return parser


@cache
def form_loader():
    """Built on first use so subcommands that never read YAML skip the import."""
    from ruamel.yaml.constructor import SafeConstructor

    class FormConstructor(SafeConstructor):
        pass

    FormConstructor.add_constructor("tag:yaml.org,2002:float", keep_text)
    FormConstructor.add_constructor("tag:yaml.org,2002:bool", keep_text)
    return yaml11(FormConstructor)


@cache
def safe_loader():
    return yaml11()


def load_form(text):
    return form_loader().load(text) or {}


def safe_load(text):
    return safe_loader().load(text)


def strip_comments(text):
    return re.sub(r"<!--.*?-->", "", text, flags=re.DOTALL)


def sections(text):
    parts = re.split(r"^(#{1,6}) (.+)$", strip_comments(text), flags=re.MULTILINE)
    found = []
    for i in range(1, len(parts), 3):
        found.append((parts[i + 1].strip(), parts[i + 2].strip(), len(parts[i])))
    return found


def front_matter(text):
    parts = re.split(r"^---\s*$", text, maxsplit=2, flags=re.MULTILINE)
    if len(parts) < 3 or parts[0].strip():
        return {}, text
    return load_form(parts[1]), parts[2]


def files_matching(clone, patterns):
    found = {}
    for pattern in patterns:
        for path in sorted(clone.glob(pattern, case_sensitive=False)):
            if path.is_file():
                found.setdefault(path)
    return list(found)


def matching_lines(path, rx):
    hits = []
    for number, line in enumerate(read(path).splitlines(), 1):
        if rx.search(line):
            hits.append((number, line.strip()[:110]))
    return hits


def policy_hits_for(clone, rx):
    hits = []
    for path in files_matching(clone, POLICY_FILES):
        rel = path.relative_to(clone)
        for number, line in matching_lines(path, rx):
            hits.append(f"{rel}:{number}: {line}")
    return hits


def policy_hits(clone):
    return {label: policy_hits_for(clone, rx) for label, rx in POLICY.items()}


def decision_records(clone):
    records = []
    for folder in ("docs/adr", "docs/decisions", ".out-of-scope"):
        for path in sorted((clone / folder).glob("*.md")):
            lines = read(path).splitlines()
            heading = next((x[2:].strip() for x in lines if x.startswith("# ")), "")
            records.append(f"{path.relative_to(clone)}: {heading or path.stem}")
    return records


def find_templates(clone, shape):
    patterns = ISSUE_TEMPLATES if shape == "issue" else PR_TEMPLATES
    found = files_matching(clone, patterns)
    return [p for p in found if p.stem.lower() != "config"]


def chooser_config(clone):
    found = files_matching(clone, (".github/ISSUE_TEMPLATE/config.y*ml",))
    return found[0] if found else None


def template_name(path):
    text = read(path)
    if path.suffix == ".md":
        return front_matter(text)[0].get("name")
    return load_form(text).get("name")


def pick_template(templates, name):
    if len(templates) <= 1:
        return templates[0] if templates else None
    for path in templates:
        if name and name in (path.name, path.stem, template_name(path)):
            return path
    names = ", ".join(p.name for p in templates)
    refuse(f"several templates, pass --template, one of: {names}")


def pr_workflows(clone):
    from ruamel.yaml import YAMLError

    found = []
    for path in sorted((clone / ".github" / "workflows").glob("*.y*ml")):
        try:
            wf = safe_load(read(path)) or {}
        except YAMLError:
            continue
        on = wf.get("on", wf.get(True))
        triggers = on if isinstance(on, (list, dict)) else [on]
        if {"pull_request", "pull_request_target"} & set(triggers):
            found.append((path, workflow_steps(wf)))
    return found


def workflow_steps(wf):
    steps = []
    for job in (wf.get("jobs") or {}).values():
        steps += job.get("steps") or []
    return steps


def title_rule(workflows):
    for _, steps in workflows:
        for step in steps:
            if "action-semantic-pull-request" not in str(step.get("uses", "")):
                continue
            opts = step.get("with") or {}
            types = str(opts.get("types", "")).split() or DEFAULT_TYPES
            return types, bool(opts.get("requireScope")), opts.get("subjectPattern")
    return None


def needs_signoff(workflows):
    text = " ".join(read(path).lower() for path, _ in workflows)
    return bool(re.search(r"signed-off-by|\bdco\b|cla-assistant|\bcla\b", text))


def run_lines(steps):
    lines = []
    for step in steps:
        if "run" in step:
            lines.append(str(step["run"]).strip().splitlines()[0][:90])
    return lines


