def is_checked(item, body):
    return re.search(r"[-*] \[[xX]\] " + re.escape(item.strip()[:45]), body)


def check_checkboxes(options, body, problems):
    for option in options:
        if option.get("required") and not is_checked(option["label"], body):
            problems.append(f"required checkbox unchecked: {option['label'][:60]}")


def check_dropdown(label, options, value, problems):
    allowed = [str(o) for o in options]
    chosen = [v.strip() for v in value.split(",")]
    if not all(v in allowed for v in chosen):
        problems.append(
            f"dropdown '{label}' must be one of {allowed}, got '{value[:40]}'"
        )


def check_form(form, body, problems):
    got = {heading: text for heading, text, _ in sections(body)}
    fields = [f for f in form.get("body", []) if f.get("type") != "markdown"]
    for field in fields:
        attrs = field.get("attributes", {})
        label = attrs.get("label")
        required = field.get("validations", {}).get("required", False)
        if field["type"] == "checkboxes":
            check_checkboxes(attrs.get("options", []), body, problems)
        elif label not in got:
            suffix = " (required)" if required else ""
            problems.append(f"form field heading missing: '### {label}'{suffix}")
        else:
            check_form_value(field, got[label], required, problems)
    print(f"form fields checked: {len(fields)}")


def check_form_value(field, value, required, problems):
    attrs = field.get("attributes", {})
    label = attrs.get("label")
    empty = value in ("", "_No response_")
    if required and empty:
        problems.append(f"required form field empty: {label}")
    if field["type"] == "dropdown" and not empty:
        check_dropdown(label, attrs.get("options", []), value, problems)


def check_markdown(template, body, title, problems, amend=False):
    meta, content = front_matter(read(template))
    content = strip_comments(content)
    want = [heading for heading, _, _ in sections(content)]
    got = sections(body)
    names = [heading for heading, _, _ in got]
    for heading in want:
        if heading not in names:
            problems.append(f"template heading missing: '{heading}'")
    if [h for h in names if h in want] != [h for h in want if h in names]:
        problems.append("template headings out of order")
    for i, (heading, text, level) in enumerate(got):
        deeper = i + 1 < len(got) and got[i + 1][2] > level
        if heading in want and not text and not deeper:
            problems.append(f"template section empty: '{heading}'")
    items = re.findall(r"^\s*[-*] \[[ xX]\] (.+)$", content, re.MULTILINE)
    for item in items:
        if not is_checked(item, body) and not amend:
            problems.append(f"template checklist item not checked: {item.strip()[:60]}")
    prefix = str(meta.get("title") or "").strip()
    if prefix and not title.startswith(prefix):
        problems.append(f"title must start with '{prefix}'")
    print(f"template headings checked: {len(want)}, checklist items: {len(items)}")


def check_layout(clone, args, body, problems, warns):
    templates = find_templates(clone, args.shape)
    template = pick_template(templates, args.template)
    if template is None:
        refuse_blank_issue(clone, args.shape)
        print("template: none in this repo, using the layout in references/bodies.md")
        check_fallback(args.shape, body, problems)
    elif template.suffix in (".yml", ".yaml"):
        print(f"template: issue form {template.name}")
        form = load_form(read(template))
        check_form(form, body, problems)
        prefix = str(form.get("title", "")).strip()
        if prefix and not args.title.startswith(prefix):
            problems.append(f"title must start with '{prefix}'")
    else:
        print(f"template: markdown {template.name}")
        check_markdown(
            template, body, args.title, problems, getattr(args, "amend", False)
        )
        if not PERMALINK.search(body):
            warns.append(
                "no SHA-pinned permalink in the body (github.com/<o>/<r>/blob/<full-40-hex-sha>/...; commit/ links and short SHAs do not count)"
            )


def refuse_blank_issue(clone, shape):
    config = chooser_config(clone)
    if shape != "issue" or not config:
        return
    settings = safe_load(read(config)) or {}
    if not settings.get("blank_issues_enabled", True):
        refuse("blank issues are disabled and no template exists")


def check_fallback(shape, body, problems):
    lowered = body.lower()
    for heading in FALLBACK_LAYOUT[shape]:
        if heading.lower() not in lowered:
            problems.append(f"fallback layout heading missing: '{heading}'")
    if not PERMALINK.search(body):
        problems.append("no SHA-pinned permalink (github.com/<o>/<r>/blob/<sha>/...)")


def check_title(workflows, title, problems):
    rule = title_rule(workflows)
    if not rule:
        return
    types, need_scope, pattern = rule
    match = TITLE.match(title)
    if not match or match.group(1) not in types:
        problems.append(f"title must be '<type>(<scope>): <subject>', type in {types}")
    elif need_scope and not match.group(3):
        problems.append("title needs a scope")
    elif pattern and not re.search(pattern, match.group(4)):
        problems.append(f"title subject must match {pattern}")


def git(clone, *argv):
    cmd = ["git", "-C", str(clone), *argv]
    return subprocess.run(cmd, capture_output=True, text=True, check=True).stdout


def added_lines(clone, base):
    diff = git(clone, "diff", "--unified=0", f"{base}...HEAD")
    added, in_hunk = [], False
    for line in diff.splitlines():
        if line.startswith("diff --git"):
            in_hunk = False
        elif line.startswith("@@"):
            in_hunk = True
        elif in_hunk and line.startswith("+"):
            added.append(line[1:])
    return added


def check_diff(lines, problems):
    for line in lines:
        text = line.strip()[:40]
        if "[DEBUG-" in line:
            problems.append(f"debug tag left in diff: {text}")
        if any(rx.search(line) for rx in SECRETS):
            problems.append(f"credential-like text in diff: {text}...")
    if not lines:
        problems.append("diff against base is empty")


def check_signoff(clone, base, problems):
    log = git(clone, "log", f"{base}..HEAD", "--format=%h%x1f%B%x1e")
    for entry in log.split("\x1e"):
        commit = entry.strip()
        if commit and "Signed-off-by:" not in commit:
            problems.append(f"commit lacks Signed-off-by: {commit[:7]}")


def check_pr(clone, args, problems):
    workflows = pr_workflows(clone)
    check_title(workflows, args.title, problems)
    if not getattr(args, "amend", False):
        check_diff(added_lines(clone, args.base), problems)
        if needs_signoff(workflows):
            check_signoff(clone, args.base, problems)


def check_policy(clone, args, body, problems):
    if args.ai_policy == "none" and policy_hits(clone)["AI policy"]:
        problems.append("AI policy lines exist: read the policy, classify it")
    disclosed = bool(args.disclosure) and body.rstrip().endswith(
        args.disclosure.strip()
    )
    if args.ai_policy == "disclose" and not disclosed:
        problems.append(
            "--ai-policy disclose needs --disclosure text as the last line of the body"
        )


def all_matches(patterns, text):
    found = []
    for rx in patterns:
        found += [m.group(0) for m in rx.finditer(text)]
    return found


def check_text(body, title, problems):
    text = body + "\n" + title
    for found in all_matches(SECRETS, text):
        problems.append(f"credential-like text in body: '{found[:30]}...'")
    for found in all_matches(PII, text):
        problems.append(f"personal path in body (use <user>): '{found}'")
    for found in all_matches([PLACEHOLDER], strip_comments(body)):
        problems.append(f"unresolved placeholder: '{found.strip()}'")


def check(args):
    clone = Path(args.clone)
    if args.ai_policy == "forbidden":
        refuse("the repo's AI policy forbids this post; report the rule")
    if args.shape == "pr" and not args.base and not getattr(args, "amend", False):
        refuse("pr check needs --base <ref> to scan the diff and commits")
    body = read(Path(args.body))
    problems, warns = [], []
    check_policy(clone, args, body, problems)
    check_layout(clone, args, body, problems, warns)
    if args.shape == "pr":
        check_pr(clone, args, problems)
    check_text(body, args.title, problems)
    for warn in warns:
        print(f"WARN {warn}")
    for problem in problems:
        print(f"FAIL {problem}")
    print("OK" if not problems else f"{len(problems)} violation(s)")
    sys.exit(1 if problems else 0)


def sh(argv, cwd=None, timeout=60):
    exe = shutil.which(argv[0])
    if not exe:
        return None
    try:
        r = subprocess.run(
            [exe, *argv[1:]],
            capture_output=True,
            text=True,
            encoding="utf-8",
            errors="replace",
            cwd=cwd,
            timeout=timeout,
        )
    except (OSError, subprocess.TimeoutExpired):
        return None
    return r.stdout.strip() if r.returncode == 0 else None


def vtuple(text):
    m = re.search(r"\d+(?:\.\d+)+", text or "")
    return tuple(map(int, m[0].split("."))) if m else None


def stale(run=sh):
    """gh and codegraph behind their latest release; an unanswerable probe counts as stale (fail closed)."""
    out = []
    for name, have, want, fix in (
        (
            "gh",
            ["gh", "--version"],
            ["gh", "api", "repos/cli/cli/releases/latest", "--jq", ".tag_name"],
            "winget upgrade GitHub.cli",
        ),
        (
            "codegraph",
            ["codegraph", "--version"],
            ["npm", "view", "@colbymchenry/codegraph", "version"],
            "npm i -g @colbymchenry/codegraph@latest",
        ),
    ):
        h, w = vtuple(run(have)), vtuple(run(want))
        if h is None or w is None or h < w:
            out.append(f"{name}: installed {h} vs latest {w}; repair: {fix}")
    return out


def latest():
    problems = stale()
    for p in problems:
        print(f"STALE: {p}", file=sys.stderr)
    if problems:
        refuse("not on the latest version; update, then rerun")
    print("latest: ok")


